"""Regenerate src/cpstands/ui/emoji_ids.py from Telegram's RestrictedEmoji custom-emoji set."""

import asyncio
from pathlib import Path

from aiogram import Bot

from cpstands.config import get_settings

PALETTE = [
    "🏆", "✅", "⚠️", "⏰", "🌍", "🗣", "👥", "📊", "⚙️", "🔔", "❌", "👋", "🚀", "⭐",
    "📅", "🌐", "🕐", "➕", "➖", "📋", "ℹ️", "🎯", "🎉", "🤖", "🔥", "💬", "🥇", "🥈",
    "🥉", "🧭", "👑", "⚡", "🔒", "🔁", "🌐", "📌", "🏁", "🧑‍💻", "🔗", "🎛️",
]  # fmt: skip
OUT = Path(__file__).resolve().parents[1] / "src" / "cpstands" / "ui" / "emoji_ids.py"


async def main() -> None:
    bot = Bot(get_settings().telegram_bot_token.get_secret_value())
    sticker_set = await bot.get_sticker_set("RestrictedEmoji")
    await bot.session.close()
    by_emoji: dict[str, str] = {}
    for sticker in sticker_set.stickers:
        if sticker.emoji and sticker.custom_emoji_id:
            by_emoji.setdefault(sticker.emoji, sticker.custom_emoji_id)
            by_emoji.setdefault(sticker.emoji.replace(chr(0xFE0F), ""), sticker.custom_emoji_id)
    found: dict[str, str] = {}
    missing: list[str] = []
    for emoji in dict.fromkeys(PALETTE):
        ident = by_emoji.get(emoji) or by_emoji.get(emoji.replace(chr(0xFE0F), ""))
        if ident:
            found[emoji] = ident
        else:
            missing.append(emoji)
    lines = [
        "# ruff: noqa: RUF001",
        '"""Custom emoji ids (set RestrictedEmoji). Generated by scripts/gen_emoji_ids.py."""',
        "",
        "CUSTOM_EMOJI_IDS: dict[str, str] = {",
    ]
    lines += [f'    "{e}": "{i}",' for e, i in found.items()]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(
        f"wrote {len(found)} ids; missing: {missing}".encode("ascii", "backslashreplace").decode()
    )


asyncio.run(main())
